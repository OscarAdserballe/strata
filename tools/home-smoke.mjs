import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base = process.argv[2] || 'http://127.0.0.1:8804';
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || undefined });
const results = [];
try {
for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
  const ctx = await browser.newContext({ viewport, serviceWorkers: 'block', isMobile: viewport.width < 500, hasTouch: viewport.width < 500 });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  let libraryReads = 0;
  page.on('request', r => { if (r.method() === 'GET' && r.url() === base + '/api/library') libraryReads++; });
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'New card', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const front = 'A quote worth keeping ' + viewport.width + ' ' + Date.now();
  await page.getByLabel('Front', { exact: true }).fill(front);
  await page.getByLabel('Back', { exact: true }).fill('Pay attention to what matters.');
  await page.getByLabel('Source or attribution (optional)').fill('My notebook');
  assert.equal(libraryReads, 0, 'creating a card does not wait for conversation or existing cards to load');
  await page.getByRole('button', { name: 'Format & Preview', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm save', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Saved to Unfiled' }).waitFor();
  await dialog.getByText(front, { exact: true }).click();
  await dialog.locator('details').filter({ hasText: front }).getByText('Pay attention to what matters.', { exact: true }).waitFor();
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  const question = 'What makes a quote memorable? ' + viewport.width + ' ' + Date.now();
  if (viewport.width >= 500) await page.keyboard.press('/');
  const line = page.locator('.ask .line input');
  await line.fill(question);
  await line.press('Enter');
  // the thread keeps earlier replies: wait for this question's own
  await page.waitForFunction((q) => { const me = [...document.querySelectorAll('.ask .turn.me')].at(-1); const line = document.querySelector('.ask .line input');
    return me && me.textContent === q && !line.disabled && me.nextElementSibling?.querySelector('.mint-c'); }, question);
  await page.locator('.ask .mint-c').last().click();
  { const got = await page.getByLabel('Front', { exact: true }).inputValue(); if (got !== question) throw new Error('reply was not captured at ' + viewport.width + ': front reads ' + JSON.stringify(got)); }
  if (!(await page.getByLabel('Back', { exact: true }).inputValue()).trim()) throw new Error('reply back is blank');
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  const asked = await (await fetch(base + '/api/boards/inbox/messages')).json();
  assert.ok(asked.messages.some(m => m.role === 'user' && m.text === question), 'the question is on the library thread');
  await line.fill('a draft worth keeping');
  await line.press('Escape');
  assert.equal(await line.inputValue(), 'a draft worth keeping');
  await line.fill('');
  if (page.url() !== base + '/') throw new Error('home tool navigated away');
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Unfiled cards', exact: true }).click();
  await dialog.getByText(front, { exact: true }).waitFor();
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  let acceptRequest, releaseSave;
  const requested = new Promise(resolve => { acceptRequest = resolve; });
  const released = new Promise(resolve => { releaseSave = resolve; });
  await page.route(base + '/api/library/cards', async route => {
    acceptRequest();
    await released;
    await route.continue();
  });
  await page.getByRole('button', { name: 'New card', exact: true }).click();
  const delayedFront = front + ' delayed';
  await page.getByLabel('Front', { exact: true }).fill(delayedFront);
  await page.getByLabel('Back', { exact: true }).fill('Finish quietly after I close.');
  await page.getByRole('button', { name: 'Format & Preview', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm save', exact: true }).click();
  await requested;
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  releaseSave();
  await page.locator('.home-tool-dialog [role="status"]').waitFor({ state: 'attached' });
  if (await dialog.isVisible()) throw new Error('a late save reopened the dialog');
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Unfiled cards', exact: true }).click();
  await dialog.getByText(delayedFront, { exact: true }).waitFor();
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await page.route(base + '/api/review', r => r.fulfill({ json: { cards: [], total: 0, unkeptDue: 0, nextDueAt: null } }));
  await page.goto(base + '/?view=review', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'new card', exact: true }).click();
  await page.locator('.rcompose .front').fill(front + ' from empty review');
  await page.locator('.rcompose .back').fill('A card can start anywhere.');
  await page.locator('.rcompose').getByRole('button', { name: 'Format & Preview', exact: true }).click();
  await page.locator('.rcompose').getByRole('button', { name: 'Confirm save', exact: true }).click();
  await page.locator('.rcompose').waitFor({ state: 'detached' });
  assert.equal(new URL(page.url()).searchParams.get('view'), 'review');
  const stored = await (await fetch(base + '/api/library')).json();
  assert.ok(stored.cards.some(c => c.front === front + ' from empty review'));
  assert.deepEqual(errors, []);
  results.push({ viewport, homeStayedPut: true, cardSurvivedReload: true, replyToCard: true, lateSaveStayedClosed: true, errors });
  await ctx.close();
}
console.log('✓ library Ask, quote cards, reload, reply-to-card, and late-save close at desktop and phone sizes');
} finally { await browser.close(); }
